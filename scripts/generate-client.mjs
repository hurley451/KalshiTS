#!/usr/bin/env node
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { createHash } from "node:crypto";
import YAML from "yaml";
import openapiTS, { astToString } from "openapi-typescript";
import { sample } from "openapi-sampler";

const arg = (name) => process.argv[process.argv.indexOf(name) + 1];
const source = process.argv.includes("--source") ? arg("--source") : process.env.KALSHI_OPENAPI;
if (!source) throw new Error("Pass --source <official openapi.yaml> or set KALSHI_OPENAPI.");
const bytes = await readFile(source);
const spec = YAML.parse(bytes.toString());
const sha256 = createHash("sha256").update(bytes).digest("hex");
const resolve = (value) => value?.$ref ? resolve(value.$ref.slice(2).split("/").reduce((v, k) => v[k], spec)) : value;
const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const entries = [];
for (const [path, item] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(item)) {
    if (!op.operationId) continue;
    const parameters = [...(item.parameters ?? []), ...(op.parameters ?? [])].map(resolve);
    const unique = [...new Map(parameters.map(p => [`${p.in}:${p.name}`, p])).values()];
    const body = resolve(op.requestBody);
    const responses = Object.fromEntries(Object.entries(op.responses).map(([status, value]) => [status, resolve(value)]));
    const domain = ({ market: "markets", milestone: "milestones" })[op.tags[0]] ?? camel(op.tags[0]);
    entries.push({ operationId: op.operationId, method: method.toUpperCase(), path, tags: op.tags,
      summary: op.summary, domain, methodName: op.operationId[0].toLowerCase() + op.operationId.slice(1),
      parameters: unique, requestBody: body, responses, authenticated: (op.security ?? spec.security ?? []).length > 0,
      repeatedQueryParameters: unique.filter(p => p.in === "query" && resolve(p.schema)?.type === "array" && (p.explode ?? (p.style ?? "form") === "form")).map(p => p.name) });
  }
}
entries.sort((a,b) => a.operationId.localeCompare(b.operationId));
if (new Set(entries.map(e => e.operationId)).size !== entries.length) throw new Error("Duplicate operation IDs");
const banner = `// Generated by scripts/generate-client.mjs; do not edit.\n// Official source SHA-256: ${sha256}\n`;
function nullableUnions(value) {
  if (Array.isArray(value)) return value.map(nullableUnions);
  if (!value || typeof value !== "object") return value;
  const node = Object.fromEntries(Object.entries(value).map(([k,v]) => [k, ["example","examples","default","enum"].includes(k) ? v : nullableUnions(v)]));
  if (node.nullable === true) {
    delete node.nullable;
    if (Object.hasOwn(node, "enum") && !node.enum.includes(null) || Object.hasOwn(node, "const") && node.const !== null) return node;
    return {anyOf:[node,{type:"null"}]};
  }
  return node;
}
await mkdir("src/generated", { recursive: true });
await writeFile("src/generated/schema.ts", banner + astToString(await openapiTS(nullableUnions(spec), {defaultNonNullable:false})));
const sourceInfo = { sourceId: "kalshi-openapi-rest", url: "https://docs.kalshi.com/openapi.yaml", version: spec.info.version, sha256, operationCount: entries.length };
await writeFile("src/generated/operations.ts", banner + `import type { HttpMethod } from "../types.js";
export interface KalshiOperation {
 readonly operationId: string; readonly method: HttpMethod; readonly path: string;
 readonly summary?: string | undefined; readonly tags: readonly string[];
 readonly repeatedQueryParameters?: readonly string[] | undefined;
}
export const officialOperationSource = ${JSON.stringify(sourceInfo, null, 2)} as const;
export const operations = ${JSON.stringify(entries.map(({operationId,method,path,summary,tags,repeatedQueryParameters})=>({operationId,method,path,summary,tags,repeatedQueryParameters})),null,2)} as const satisfies readonly KalshiOperation[];
export type OperationId = (typeof operations)[number]["operationId"];
export const operationsById = Object.freeze(Object.fromEntries(operations.map(o => [o.operationId, o]))) as unknown as Readonly<Record<OperationId, KalshiOperation>>;
`);
await writeFile("src/generated/contracts.ts", banner + `export const contractComponents: Record<string, unknown> = ${JSON.stringify(spec.components)};
export const operationContracts: Record<string, OperationContract> = ${JSON.stringify(Object.fromEntries(entries.map(e => [e.operationId, e])))};
export interface ParameterContract { [key:string]: unknown; name: string; in: string; required?: boolean; schema?: Record<string, unknown>; style?: string; explode?: boolean; allowReserved?: boolean }
export interface MediaContract { [key:string]: unknown; schema?: Record<string, unknown> }
export interface ResponseContract { [key:string]: unknown; content?: Record<string, MediaContract> }
export interface OperationContract { [key:string]: unknown; operationId: string; method: string; path: string; domain: string; methodName: string; parameters: ParameterContract[]; requestBody?: { [key:string]: unknown; required?: boolean; content: Record<string, MediaContract> }; responses: Record<string, ResponseContract> }
`);
let models = banner + `import type { components, operations } from "./schema.js";
export type KalshiModels = components["schemas"];
export type TypedOperationId = keyof operations;
type Content<T> = T extends { content: infer C } ? C[keyof C] : undefined;
type ResponseBody<T, S> = S extends 204 ? undefined : T extends { content: infer C } ? C[keyof C] : unknown;
type SuccessKey<T> = Extract<keyof T, number> extends infer K ? K extends number ? \`\${K}\` extends \`2\${string}\` ? K : never : never : never;
type ResponseMap<I extends TypedOperationId> = operations[I]["responses"];
export type OperationResponse<I extends TypedOperationId> = { [S in SuccessKey<ResponseMap<I>>]: ResponseBody<ResponseMap<I>[S], S> }[SuccessKey<ResponseMap<I>>];
export type OperationError<I extends TypedOperationId> = { [S in Exclude<keyof ResponseMap<I>, SuccessKey<ResponseMap<I>>>]: { status: S; body: ResponseBody<ResponseMap<I>[S], S> } }[Exclude<keyof ResponseMap<I>, SuccessKey<ResponseMap<I>>>];
type Params<I extends TypedOperationId> = operations[I]["parameters"];
type Part<I extends TypedOperationId, K extends string, N extends string> = K extends keyof Params<I> ? [NonNullable<Params<I>[K]>] extends [never] ? { [P in N]?: never } : {} extends NonNullable<Params<I>[K]> ? { [P in N]?: NonNullable<Params<I>[K]> } : { [P in N]: NonNullable<Params<I>[K]> } : { [P in N]?: never };
type Body<I extends TypedOperationId> = "requestBody" extends keyof operations[I] ? [NonNullable<operations[I]["requestBody"]>] extends [never] ? { body?: never } : operations[I] extends { requestBody: unknown } ? { body: Content<NonNullable<operations[I]["requestBody"]>> } : { body?: Content<NonNullable<operations[I]["requestBody"]>> } : { body?: never };
export type OperationInput<I extends TypedOperationId> = Part<I, "path", "pathParameters"> & Part<I, "query", "query"> & Part<I, "header", "parameterHeaders"> & Part<I, "cookie", "cookies"> & Body<I>;
export interface EndpointOptions { headers?: Record<string,string>; authenticated?: boolean }
export type EndpointArguments<I extends TypedOperationId> = {} extends OperationInput<I> ? [input?: OperationInput<I>, options?: EndpointOptions] : [input: OperationInput<I>, options?: EndpointOptions];
`;
for (const name of Object.keys(spec.components.schemas)) {
  models += `export type ${name}Model = KalshiModels[${JSON.stringify(name)}];\n`;
  models += `export type ${name === "Fill" ? "OfficialFill" : name} = KalshiModels[${JSON.stringify(name)}];\n`;
}
for (const e of entries) models += `export type ${e.operationId}Input = OperationInput<${JSON.stringify(e.operationId)}>;\nexport type ${e.operationId}Result = OperationResponse<${JSON.stringify(e.operationId)}>;\nexport type ${e.operationId}Error = OperationError<${JSON.stringify(e.operationId)}>;\n`;
await writeFile("src/generated/models.ts", models);
let client = banner + `import type { TypedOperationId, EndpointArguments, EndpointOptions, OperationResponse } from "./models.js";
export abstract class TypedEndpoints {
 protected abstract executeTyped(id: TypedOperationId, input?: unknown, options?: EndpointOptions): Promise<unknown>;
`;
for (const e of entries) client += ` ${e.methodName}(...args: EndpointArguments<${JSON.stringify(e.operationId)}>): Promise<OperationResponse<${JSON.stringify(e.operationId)}>> { return this.executeTyped(${JSON.stringify(e.operationId)}, ...args) as Promise<OperationResponse<${JSON.stringify(e.operationId)}>>; }\n`;
for (const domain of new Set(entries.map(e=>e.domain))) {
  client += ` readonly ${domain === "portfolio" ? "portfolioApi" : domain}: Pick<TypedEndpoints, ${entries.filter(e=>e.domain===domain).map(e=>JSON.stringify(e.methodName)).join(" | ")}> = {\n`;
  for (const e of entries.filter(e=>e.domain===domain)) client += `  ${e.methodName}: this.${e.methodName}.bind(this),\n`;
  client += ` };\n`;
}
client += "}\n";
await writeFile("src/generated/endpoints.ts", client);
await writeFile("src/generated/coverage.json", JSON.stringify({ ...sourceInfo, schemaCount: Object.keys(spec.components.schemas).length, domainCount: new Set(entries.map(e=>e.domain)).size,
 operations: entries.map(e=>({ operationId:e.operationId, method:e.method, path:e.path, domain:e.domain, namedMethod:e.methodName,
 parameters:e.parameters.map(p=>({name:p.name,in:p.in,required:p.required??false,style:p.style??(p.in==="query"?"form":"simple"),explode:p.explode??p.in==="query",schema:p.schema})),requestBody:e.requestBody??null,responses:e.responses,
 proof: { runtime:"test/typed-endpoints.test.ts", types:"test/typed-contracts.test.ts" } })) },null,2)+"\n");
console.log(`Generated ${entries.length} named endpoints, ${Object.keys(spec.components.schemas).length} schemas, ${new Set(entries.map(e=>e.domain)).size} facades (${sha256}).`);
const fixtures = [];
let proof = banner + `import type { KalshiClient, KalshiModels, OperationError, ${entries.map(e=>`${e.operationId}Result`).join(", ")} } from "../src/index.js";\nfunction typeProof(client: KalshiClient) {\n`;
for (const e of entries) {
  const input = {};
  for (const p of e.parameters) {
    const key = {path:"pathParameters",query:"query",header:"parameterHeaders",cookie:"cookies"}[p.in];
    (input[key] ??= {})[p.name] = sample(p.schema ?? {}, {}, spec);
  }
  if (e.requestBody) input.body = sample(e.requestBody.content["application/json"].schema, {skipNonRequired:true}, spec);
  const responses = Object.entries(e.responses).map(([status,r]) => ({status:Number(status), ...(r.content?.["application/json"]?.schema ? {body:sample(r.content["application/json"].schema,{skipNonRequired:true},spec)} : {})}));
  fixtures.push({operationId:e.operationId,methodName:e.methodName,domain:e.domain,input,responses});
  proof += ` const ${e.methodName}: Promise<${e.operationId}Result> = client.${e.methodName}(${JSON.stringify(input)});\n void ${e.methodName};\n`;
  proof += ` // @ts-expect-error Unknown query fields are not part of the official contract.\n client.${e.methodName}(${JSON.stringify({...input,query:{__notOfficial:true}})});\n`;
  for (const p of e.parameters) {
    const key = p.in === "path" ? "pathParameters" : "query";
    proof += ` // @ts-expect-error Official parameter types reject objects.\n client.${e.methodName}(${JSON.stringify({...input,[key]:{...input[key],[p.name]:{wrong:"type"}}})});\n`;
  }
  if (e.requestBody) proof += ` // @ts-expect-error Request bodies must match the official schema.\n client.${e.methodName}(${JSON.stringify({...input,body:42})});\n`;
  for (const r of responses) {
    if (r.status < 300) proof += ` const result${e.operationId}${r.status}: ${e.operationId}Result = ${JSON.stringify(r.body) ?? "undefined"};\n void result${e.operationId}${r.status};\n`;
    else proof += ` const error${e.operationId}${r.status}: OperationError<${JSON.stringify(e.operationId)}> = ${JSON.stringify(r.body === undefined ? {status:r.status} : {status:r.status,body:r.body}).replace(/}$/,r.body === undefined ? ",body:undefined}" : "}")};\n void error${e.operationId}${r.status};\n`;
  }
  proof += ` // @ts-expect-error Undeclared error statuses cannot be claimed as official.\n const bad${e.operationId}: OperationError<${JSON.stringify(e.operationId)}> = {status: -1, body: undefined};\n void bad${e.operationId};\n`;
  if (e.parameters.some(p=>p.required) || e.requestBody?.required) proof += ` // @ts-expect-error Required endpoint inputs cannot be omitted.\n client.${e.methodName}();\n`;
}
const schemaFixtures = Object.entries(spec.components.schemas).map(([name,schema]) => {
  const value = sample(schema,{skipNonRequired:true},spec);
  proof += ` const model${name}: KalshiModels[${JSON.stringify(name)}] = ${JSON.stringify(value)};\n void model${name};\n`;
  const invalid = schema.type === "object" || schema.properties ? 42 : schema.type === "integer" || schema.type === "number" ? "wrong" : {};
  proof += ` // @ts-expect-error Models reject incompatible JSON types.\n const badModel${name}: KalshiModels[${JSON.stringify(name)}] = ${JSON.stringify(invalid)};\n void badModel${name};\n`;
  for (const key of schema.required ?? []) {
    const missing = {...value}; delete missing[key];
    proof += ` // @ts-expect-error Required model properties cannot be omitted.\n const missing${name}${key}: KalshiModels[${JSON.stringify(name)}] = ${JSON.stringify(missing)};\n void missing${name}${key};\n`;
  }
  for (const [key,property] of Object.entries(schema.properties ?? {})) {
    if (property.nullable === true) proof += ` const nullable${name}${key}: KalshiModels[${JSON.stringify(name)}] = ${JSON.stringify({...value,[key]:null})};\n void nullable${name}${key};\n`;
    const resolved = resolve(property);
    if (resolved.enum) proof += ` // @ts-expect-error Model enums reject values outside the official enum.\n const enum${name}${key}: KalshiModels[${JSON.stringify(name)}] = ${JSON.stringify({...value,[key]:"__outside_enum__"})};\n void enum${name}${key};\n`;
  }
  return {name,value};
});
proof += "}\nvoid typeProof;\n";
await writeFile("test/typed-contracts.test.ts", proof);
await writeFile("test/typed-fixtures.json", JSON.stringify({sha256,fixtures,schemaFixtures},null,2)+"\n");
const schemaCoverage = [];
function visitSchema(node, pointer) {
  if (!node || typeof node !== "object") return;
  if (!Array.isArray(node)) {
    const keys = ["$ref","type","enum","nullable","required","allOf","oneOf","anyOf","minimum","maximum","exclusiveMinimum","exclusiveMaximum","multipleOf","minLength","maxLength","pattern","minItems","maxItems","uniqueItems","minProperties","maxProperties","additionalProperties","format"];
    const keywords = Object.fromEntries(keys.filter(k=>Object.hasOwn(node,k)).map(k=>[k,node[k]]));
    if (Object.keys(keywords).length) schemaCoverage.push({pointer,keywords});
  }
  for (const [key,value] of Object.entries(node)) if (value && typeof value === "object") visitSchema(value, `${pointer}/${key}`);
}
visitSchema(spec.components,"#/components");
for (const e of entries) { visitSchema(e.parameters,`#/operations/${e.operationId}/parameters`); visitSchema(e.requestBody,`#/operations/${e.operationId}/requestBody`); visitSchema(e.responses,`#/operations/${e.operationId}/responses`); }
await writeFile("src/generated/schema-coverage.json",JSON.stringify({sha256,schemaCount:schemaFixtures.length,nodes:schemaCoverage},null,2)+"\n");
