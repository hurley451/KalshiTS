#!/usr/bin/env node

import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const kalshiCoreRoot = resolveOption("--kalshicore-root") ?? process.env.KALSHICORE_ROOT;
if (!kalshiCoreRoot) {
  throw new Error("Set KALSHICORE_ROOT or pass --kalshicore-root <path>.");
}

const root = path.resolve(kalshiCoreRoot);
const inventoryPath = path.join(root, "sources", "official", "rest-openapi-operations.json");
const inventory = JSON.parse(await readFile(inventoryPath, "utf8"));

if (!Array.isArray(inventory.operations)) {
  throw new Error(`${inventoryPath} does not contain an operations array.`);
}

const operations = inventory.operations.map((operation) => ({
  operationId: readString(operation, "operationId"),
  method: readMethod(operation),
  path: readString(operation, "path"),
  ...(typeof operation.summary === "string" ? { summary: operation.summary } : {}),
  ...(Array.isArray(operation.tags) ? { tags: operation.tags.filter((tag) => typeof tag === "string") } : {})
}));

const operationIds = new Set();
for (const operation of operations) {
  if (operationIds.has(operation.operationId)) {
    throw new Error(`Duplicate operationId ${operation.operationId}`);
  }
  operationIds.add(operation.operationId);
}

const outputPath = path.resolve(resolveOption("--out") ?? "src/generated/operations.ts");
await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, renderOperations(inventory, operations), "utf8");
console.log(`Generated ${operations.length} operations at ${outputPath}`);

function renderOperations(inventory, operations) {
  return `// Generated by scripts/generate-operations.mjs from KalshiCore official sources.
// Source: ${inventory.url}
// Version: ${inventory.version}
// SHA-256: ${inventory.sha256}

import type { HttpMethod } from "../types.js";

export interface KalshiOperation {
  readonly operationId: string;
  readonly method: HttpMethod;
  readonly path: string;
  readonly summary?: string | undefined;
  readonly tags: readonly string[];
}

export const officialOperationSource = {
  sourceId: ${JSON.stringify(inventory.sourceId)},
  url: ${JSON.stringify(inventory.url)},
  version: ${JSON.stringify(inventory.version)},
  sha256: ${JSON.stringify(inventory.sha256)},
  operationCount: ${operations.length}
} as const;

export const operations = ${JSON.stringify(operations, null, 2)} as const satisfies readonly KalshiOperation[];

export type OperationId = (typeof operations)[number]["operationId"];

export const operationsById = Object.freeze(Object.fromEntries(
  operations.map((operation) => [operation.operationId, operation])
)) as unknown as Readonly<Record<OperationId, KalshiOperation>>;
`;
}

function readString(body, name) {
  const value = body[name];
  if (typeof value !== "string" || value.length === 0) {
    throw new Error(`${name} must be a non-empty string.`);
  }
  return value;
}

function readMethod(operation) {
  const method = readString(operation, "method").toUpperCase();
  if (!["GET", "POST", "PUT", "PATCH", "DELETE"].includes(method)) {
    throw new Error(`Unsupported method ${method} for ${operation.operationId}`);
  }
  return method;
}

function resolveOption(name) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : undefined;
}
